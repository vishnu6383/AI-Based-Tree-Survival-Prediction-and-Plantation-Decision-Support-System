"""
Application Configuration Settings
==================================
Manages environment variables, risk thresholds, and database connection strings.
"""

import os
from pathlib import Path
from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent.parent
load_dotenv(BASE_DIR / ".env")

class Settings:
    PROJECT_NAME: str = "AI-Based Tree Survival Prediction and Decision Support System"
    VERSION: str = "1.0.0"
    API_PREFIX: str = "/api"

    # CORS configuration
    FRONTEND_URL: str = os.getenv("FRONTEND_URL", "http://localhost:5173")
    CORS_ORIGINS: list = [
        "http://localhost:5173",
        "http://127.0.0.1:5173",
        "http://localhost:3000",
        "http://127.0.0.1:3000",
        "*"
    ]

    # Model & Storage Paths
    MODEL_PATH: str = os.getenv(
        "MODEL_PATH",
        str(BASE_DIR / "model" / "tree_survival_random_forest.joblib")
    )
    METRICS_PATH: str = os.getenv(
        "METRICS_PATH",
        str(BASE_DIR / "model" / "model_metrics.json")
    )
    FEATURE_IMPORTANCE_PATH: str = os.getenv(
        "FEATURE_IMPORTANCE_PATH",
        str(BASE_DIR / "model" / "feature_importance.json")
    )

    # MongoDB Connection
    MONGODB_URI: str = os.getenv("MONGODB_URI", "mongodb://localhost:27017")
    DB_NAME: str = os.getenv("DB_NAME", "tree_survival_db")
    COLLECTION_NAME: str = os.getenv("COLLECTION_NAME", "predictions")

    # Configurable Risk Classification Thresholds
    # Survival Probability >= HIGH_THRESHOLD -> Low Risk / Likely to Thrive
    # Survival Probability >= MEDIUM_THRESHOLD -> Medium Risk / Moderate Viability
    # Survival Probability < MEDIUM_THRESHOLD -> High Risk / Unfavorable
    THRESHOLD_HIGH_SURVIVAL: float = float(os.getenv("THRESHOLD_HIGH_SURVIVAL", "0.68"))
    THRESHOLD_MODERATE_SURVIVAL: float = float(os.getenv("THRESHOLD_MODERATE_SURVIVAL", "0.45"))

    # Academic Disclaimer
    ACADEMIC_NOTICE: str = (
        "Notice: This prediction is generated by an academic Random Forest decision-support system "
        "trained on synthetic environmental variation data. Field-validated soil tests and local forestry "
        "expert consultation are recommended prior to large-scale afforestation."
    )

settings = Settings()
